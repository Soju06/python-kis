from __future__ import annotations

import shutil
from pathlib import Path

from codegen.core.format import run_ruff_fix, run_ruff_format
from codegen.streaming.models import FieldSpec, StreamingSpecRoot, TrSpec

HEADER = """# Generated by pykis codegen. DO NOT EDIT.
"""


def generate_streaming_raw(spec: StreamingSpecRoot, output_dir: Path) -> int:
    if output_dir.exists():
        shutil.rmtree(output_dir)
    output_dir.mkdir(parents=True, exist_ok=True)

    generated = 0
    modules: list[str] = []
    for tr_id in sorted(spec.tr_specs.keys()):
        tr_spec = spec.tr_specs[tr_id]
        module_name = tr_id.lower()
        modules.append(module_name)
        file_path = output_dir / f"{module_name}.py"
        content = render_model_module(tr_spec)
        file_path.write_text(content, encoding="utf-8")
        generated += 1

    _write_registry(spec, output_dir)
    _write_init(output_dir)

    run_ruff_fix(output_dir.rglob("*.py"))
    run_ruff_format(output_dir.rglob("*.py"))

    return generated


def render_model_module(tr_spec: TrSpec) -> str:
    field_names = tr_spec.field_order_normalized or tr_spec.field_order
    field_specs = tr_spec.field_specs

    needs_decimal = any(field_specs[name].field_type == "decimal" for name in field_names)
    needs_datetime = any(field_specs[name].field_type == "datetime" for name in field_names)

    lines: list[str] = []
    lines.append(HEADER.rstrip())
    lines.append("from __future__ import annotations")
    lines.append("")

    imports: list[str] = []
    if needs_datetime:
        imports.insert(0, "from datetime import datetime")
    if needs_decimal:
        imports.insert(0, "from decimal import Decimal")

    imports.append("from pykis.streaming.raw.base import StreamingRawModel")
    imports.append(
        "from pykis.streaming.raw.specs import DateTimeRule, DecimalRule, FieldSource, FieldType, StreamingSpec"
    )

    lines.extend(imports)
    lines.append("")

    class_name = _class_name(tr_spec.tr_id)
    lines.append(f"class {class_name}(StreamingRawModel):")
    for name in field_names:
        spec = field_specs[name]
        lines.append(f"    {name}: {_type_annotation(spec)}")
    lines.append("")

    lines.append(f"FIELD_ORDER = {list(tr_spec.field_order)!r}")
    if tr_spec.field_aliases:
        lines.append(f"FIELD_ALIASES = {dict(tr_spec.field_aliases)!r}")
    else:
        lines.append("FIELD_ALIASES = {}")

    lines.append("FIELD_TYPES = {")
    for name in field_names:
        spec = field_specs[name]
        lines.append(f"    {name!r}: FieldType.{spec.field_type.upper()},")
    lines.append("}")

    lines.append("FIELD_SOURCES = {")
    for name in field_names:
        spec = field_specs[name]
        lines.append(f"    {name!r}: FieldSource.{spec.source.upper()},")
    lines.append("}")

    lines.append("DATETIME_RULES = {")
    for name in field_names:
        spec = field_specs[name]
        if spec.datetime_rule is None:
            continue
        rule = spec.datetime_rule
        args = [f"kind={rule.kind!r}", f"format={rule.format!r}", f"timezone={rule.timezone!r}"]
        if rule.date_field:
            args.append(f"date_field={rule.date_field!r}")
        if rule.year_policy:
            args.append(f"year_policy={rule.year_policy!r}")
        joined = ", ".join(args)
        lines.append(f"    {name!r}: DateTimeRule({joined}),")
    lines.append("}")

    lines.append("DECIMAL_RULES = {")
    for name in field_names:
        spec = field_specs[name]
        if spec.decimal_rule is None:
            continue
        rule = spec.decimal_rule
        lines.append(f"    {name!r}: DecimalRule(scale={rule.scale!r}, zdiv_field={rule.zdiv_field!r}),")
    lines.append("}")

    lines.append(
        "SPEC = StreamingSpec(\n"
        f"    tr_id={tr_spec.tr_id!r},\n"
        f"    endpoint_uuid={tr_spec.endpoint_uuid!r},\n"
        f"    market={tr_spec.market!r},\n"
        f"    timezone_hint={tr_spec.timezone!r},\n"
        f"    model={class_name},\n"
        "    field_order=tuple(FIELD_ORDER),\n"
        "    field_aliases=FIELD_ALIASES,\n"
        "    field_types=FIELD_TYPES,\n"
        "    field_sources=FIELD_SOURCES,\n"
        "    datetime_rules=DATETIME_RULES,\n"
        "    decimal_rules=DECIMAL_RULES,\n"
        f"    requires_business_date={tr_spec.requires_business_date!r},\n"
        ")"
    )

    lines.append("")
    lines.append(
        "__all__ = [\n"
        f"    {class_name!r},\n"
        '    "SPEC",\n'
        '    "FIELD_ORDER",\n'
        '    "FIELD_ALIASES",\n'
        '    "FIELD_TYPES",\n'
        '    "FIELD_SOURCES",\n'
        '    "DATETIME_RULES",\n'
        '    "DECIMAL_RULES",\n'
        "]"
    )

    return "\n".join(lines) + "\n"


def _class_name(tr_id: str) -> str:
    if not tr_id:
        return "StreamingEvent"
    name = "".join(ch if ch.isalnum() else "_" for ch in tr_id)
    if name[0].isdigit():
        name = f"_{name}"
    return name


def _type_annotation(spec: FieldSpec) -> str:
    if spec.field_type == "decimal":
        return "Decimal"
    if spec.field_type == "int":
        return "int"
    if spec.field_type == "datetime":
        return "datetime"
    return "str"


def _write_registry(spec: StreamingSpecRoot, output_dir: Path) -> None:
    lines: list[str] = []
    lines.append(HEADER.rstrip())
    lines.append("from __future__ import annotations")
    lines.append("")
    lines.append("from pykis.streaming.raw.specs import StreamingSpec")

    entries = []
    for tr_id in sorted(spec.tr_specs.keys()):
        module_name = tr_id.lower()
        class_name = _class_name(tr_id)
        alias = f"{class_name}_SPEC"
        lines.append(f"from pykis.streaming.raw.generated.{module_name} import SPEC as {alias}")
        entries.append((tr_id, alias))

    lines.append("")
    lines.append("REGISTRY: dict[str, StreamingSpec] = {")
    for tr_id, alias in entries:
        lines.append(f"    {tr_id!r}: {alias},")
    lines.append("}")
    lines.append("")
    lines.append('__all__ = ["REGISTRY"]')

    (output_dir / "registry.py").write_text("\n".join(lines) + "\n", encoding="utf-8")


def _write_init(output_dir: Path) -> None:
    lines = [
        HEADER.rstrip(),
        "from __future__ import annotations",
        "",
        "from pykis.streaming.raw.generated.registry import REGISTRY",
        "",
        '__all__ = ["REGISTRY"]',
    ]
    (output_dir / "__init__.py").write_text("\n".join(lines) + "\n", encoding="utf-8")
