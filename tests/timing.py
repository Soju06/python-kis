"""타이밍 단언의 여유값. 레이트리밋 테스트 두 파일이 함께 씁니다.

- `tests/unit/utils/test_rate_limit_accuracy.py`
- `tests/integration/test_rate_limit_compliance.py`

앞 파일에만 있던 처방이 뒤 파일에 오지 않아 이슈 #92 가 났습니다. 둘은 원래
`tests/unit/` 에 함께 있었고 #41 이 하나를 옮기면서 갈라졌습니다. 값을 한 곳에
두면 다음 이동에서 다시 갈라지지 않습니다.

`tests/env.py` 와 같은 방식으로 import 합니다 — `pyproject.toml` 의
`pythonpath = ["."]` 에 의존합니다. `tests/` 에 `__init__.py` 를 넣지 마세요.

## 모든 상한에 이 여유를 얹으면 안 됩니다

타이밍 **하한**은 언제나 유량 제한기의 성질입니다 — "제한이 실제로 걸렸는가".
엄격하게 둡니다. **상한**은 머신 속도와 스케줄링의 성질이라 여유가 필요한데,
**무엇을 묻는 상한이냐에 따라 여유의 최대치가 다릅니다.**

| 묻는 것 | 상한 | 여유의 최대치 |
|---|---|---|
| "N주기 기다렸는가" | `N + SCHEDULING_SLACK` | 하한이 진짜 검사를 하므로 한 주기를 넘어도 된다 |
| "기다리지 **않았는가**" | 한 주기보다 **작은** 값 | 한 주기 이상이면 "한 주기 기다림"과 구분이 사라진다 |

두 번째 칸에 `SCHEDULING_SLACK`(2.0)을 얹으면 주기(1.0)를 넘으므로
**유량 제한이 통째로 사라져도 통과**합니다. #92 를 고치면서 실제로
`< 0.1`, `< 0.5`, `< 1.0` 세 곳에 2.0 을 얹을 뻔했습니다.

세 곳은 손대지 않았습니다. **얹을 필요가 없어서가 아니라, 재 봤더니 여유가
1000배 이상이라 플레이크의 후보가 아니었기 때문입니다.** CPU 16배 과부하에서
`< 0.5` 자리의 실측 최대가 0.0001초였습니다. 근거는
`docs/dev_logs/2026-08-30_10_issue92_flake.md` 에 있습니다.
"""

#: "N주기 기다렸는가"를 보는 상한에 얹는 여유(초).
#:
#: 하한은 "유량 제한이 실제로 걸렸는가"를 검증하므로 엄격하게 둔다. 반면 상한은
#: 머신 속도와 스케줄링에만 좌우된다. 전체 스위트는 CPU를 포화시키는 벤치마크와
#: 함께 돌고 CI 는 `--cov` 까지 켜기 때문에, 기대값에 0.3~0.4초만 얹은 상한은
#: 부하가 걸릴 때 터진다. 실제로 `test_rate_limiter_with_very_low_limit` 이
#: 단독 실행에서는 5/5 통과하면서 전체 실행에서만 실패했다(이슈 #59).
#:
#: **이 상한이 못 잡는 것을 적어 둡니다.** 주기가 1.0초일 때 이 여유는 두 주기가
#: 넘습니다. 그러므로 **대기가 한두 주기 늘어나는 회귀(과대 대기)는 상한도
#: 하한도 잡지 못합니다** — 상한은 여유 안이고, 하한은 넘치는 쪽이라 더 만족될
#: 뿐입니다.
#:
#: 그 트레이드오프를 받아들입니다. 이 테스트들이 지키는 것은 **과소 대기**, 즉
#: "유량 제한이 안 걸리는" 회귀이고 그쪽은 하한이 잡습니다. 과소 대기는 API
#: 차단을 부르고, 과대 대기는 느릴 뿐입니다.
#:
#: (`test_rate_limit_accuracy.py` 는 "대기가 한 주기 더 늘어나는 회귀는 이
#: 여유보다 크므로 상한이 여전히 잡는다"고 적고 있었습니다. 1.0 < 2.0 이므로
#: 틀린 문장이었고 #92 에서 고쳤습니다.)
SCHEDULING_SLACK = 2.0


def assert_band(
    times: list[float],
    *,
    lo: float,
    hi: float,
    offset: int = 0,
    label: str,
) -> None:
    """구간 밖으로 나간 요청을 **전부** 번호와 실제 시각으로 알려 준다.

    원래 이 검사는 이렇게 쓰여 있었다.

        assert all(1.0 <= t < 2.5 for t in request_times[10:20])

    실패하면 pytest 가 찍는 것이 이게 전부다.

        E   assert False
        E    +  where False = all(<generator object ... at 0x73f7f058dfc0>)

    **어느 요청이 언제였는지가 없다.** #92 를 조사할 때 "얼마나 늦었나"를 알려면
    실패를 다시 재현시키는 것 말고는 방법이 없었고, 세 조건 26회를 돌려도 한 번도
    재현되지 않았다. 즉 이 메시지가 없으면 **다음 실패도 같은 값을 알려주지
    않는다.** 이 함수의 가치는 대부분 거기에 있다.

    `offset` 은 잘라 낸 구간의 시작 번호다. `request_times[10:20]` 을 넘기면서
    `offset=10` 을 주면 메시지에 원래 번호가 찍힌다.
    """
    out = [(offset + i, t) for i, t in enumerate(times) if not lo <= t <= hi]

    assert not out, (
        f"{label}: {len(out)}/{len(times)}건이 [{lo:.2f}, {hi:.2f}]초 밖입니다 — "
        + ", ".join(f"{i}번={t:.3f}s" for i, t in out)
        + f"\n구간 전체: {[round(t, 3) for t in times]}"
    )
